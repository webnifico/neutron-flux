def bind_operations(owner: OperationOwner) -> dict[str, Callable[[TestSpec], None]]:
    """Bind the immutable operation contract once for a ``TestEngine``."""

    return {
        operation: getattr(owner, method_name)
        for operation, method_name in OPERATION_METHODS.items()
    }
