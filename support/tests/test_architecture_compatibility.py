def test_modular_facades_preserve_public_method_surface():
    classes = {
        "ResourceBuilder": ResourceBuilder,
        "TestEngine": FluxTestEngine,
        "Planner": Planner,
        "CleanupManager": CleanupManager,
        "AdaptiveExecutor": AdaptiveExecutor,
        "Reporter": Reporter,
    }
    for name, expected in EXPECTED_METHODS.items():
        missing = sorted(
            method for method in expected if not hasattr(classes[name], method)
        )
        assert not missing, f"{name} lost compatibility methods: {missing}"


def test_legacy_import_surface_remains_available():
    assert LaunchSelection.__name__ == "LaunchSelection"
    assert SecurityGroupBundle.__name__ == "SecurityGroupBundle"
    assert callable(resolve_launch_selection)
    assert callable(Config.from_args)
